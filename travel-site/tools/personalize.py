#!/usr/bin/env python3
"""Turn the site into a deployable folder with YOUR details filled in.

    cp tools/brand.example.json brand.json      # edit it (brand.json is git-ignored)
    python3 tools/personalize.py brand.json     # writes ./dist  (upload that folder to Cloudflare Pages / Netlify)

What it does: fills every placeholder, refuses to finish if any placeholder is left, writes the sitemap date,
and builds a strict Content-Security-Policy whose script allow-list is the SHA-256 of your own inline scripts
(so nothing injected can run). Standard library only.
"""
import argparse, base64, datetime, hashlib, json, os, re, shutil, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COPY = ["index.html", "404.html", "robots.txt", "sitemap.xml", "favicon.svg", "og-image.png", "_headers.template", "fonts", "img", "video"]
COPY += [f"{r['slug']}/index.html" for f in ("routes.json", "legal.json") for r in json.loads((ROOT / "tools" / f).read_text(encoding="utf-8"))]   # generated by build_routes.py
TEXT = {".html", ".txt", ".xml"}
MARKER = ".personalized"


def die(msg):
    sys.exit(f"personalize: {msg}")


def load(path, allow_example):
    # On a host like Vercel the private brand.json is not in git: the same JSON can come from the BRAND_JSON environment variable.
    try:
        if not Path(path).exists() and os.environ.get("BRAND_JSON"):
            b = json.loads(os.environ["BRAND_JSON"])
        else:
            b = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        die(f"cannot read {path} (or BRAND_JSON) as JSON ({e})")
    if not isinstance(b, dict):
        die(f"{path} must contain a JSON object")
    need = ["brand", "domain", "whatsapp", "instagram", "founder", "legal_name", "email", "address"]
    miss = [k for k in need if not str(b.get(k, "")).strip()]
    if miss:
        die("brand.json is missing: " + ", ".join(miss))
    if not allow_example and (b["domain"] == "yourdomain.com" or b["brand"] == "Your Brand"):
        die("brand.json still has the example values")
    if not re.fullmatch(r"(?!-)[a-z0-9-]+(\.[a-z0-9-]+)+", b["domain"]):
        die("domain must be a bare hostname like example.com (no https://, no slash)")
    if not re.fullmatch(r"\d{11,15}", b["whatsapp"]):
        die("whatsapp must be digits only with country code, e.g. 919876543210")
    if not re.fullmatch(r"[A-Za-z0-9._]{1,30}", b["instagram"]):
        die("instagram must be the handle without @")
    if not re.fullmatch(r"[^@\s<>\"]+@[^@\s<>\"]+\.[A-Za-z]{2,}", b["email"]):
        die("email must look like name@example.com")
    if not 2 <= len(b["legal_name"]) <= 80 or not 5 <= len(b["address"]) <= 200:
        die("legal_name (2-80 chars) and address (5-200 chars) are needed for the Terms, Refund and Privacy pages")
    if not allow_example and b.get("legal_reviewed") is not True:
        die("set \"legal_reviewed\": true in brand.json once you have read the Terms, Refund and Privacy pages (terms/, refunds/, privacy/) and are happy with every promise in them. They are drafts until you do.")
    if len(b["brand"]) > 40 or len(b["founder"]) > 60:
        die("brand (max 40) or founder (max 60) is too long")
    b.setdefault("phone", "+" + b["whatsapp"])
    ud = b.get("udyam", "").strip()
    if ud and not re.fullmatch(r"UDYAM-[A-Z]{2}-\d{2}-\d{7}", ud):
        die("udyam must look like UDYAM-MH-00-0000000, or leave it empty to hide the badge")
    api = b.get("api_base", "").strip().rstrip("/")
    if api and not re.fullmatch(r"https://[A-Za-z0-9.-]+(:\d+)?", api):
        die("api_base must be an https origin like https://api.example.com (no path), or empty for WhatsApp-only mode")
    b["udyam"], b["api_base"] = ud, api
    tok = str(b.get("analytics_token", "")).strip()
    if tok and not re.fullmatch(r"[A-Za-z0-9]{16,64}", tok):
        die("analytics_token must be the Cloudflare Web Analytics token (letters and digits), or empty for no analytics")
    b["analytics_token"] = tok
    tsk = str(b.get("turnstile_site_key", "")).strip()
    if tsk and not re.fullmatch(r"[A-Za-z0-9_-]{10,64}", tsk):
        die("turnstile_site_key must be the public Cloudflare Turnstile site key, or empty for no bot check")
    if tsk and not api:
        die("turnstile_site_key needs api_base: the check protects the backend form, and WhatsApp-only mode has none")
    b["turnstile_site_key"] = tsk
    rv = b.get("reviews", [])
    if not isinstance(rv, list) or len(rv) > 6:
        die("reviews must be a list of at most 6 entries")
    for r in rv:
        if not isinstance(r, dict) or r.get("consent") is not True:
            die('every review needs "consent": true. Publish a review only if the customer agreed, in writing, to have it (and their name) on your website.')
        q, n, m = r.get("quote"), r.get("name"), r.get("meta", "")
        if not all(isinstance(x, str) for x in (q, n, m)) or not 10 <= len(q) <= 400 or not 2 <= len(n) <= 60 or len(m) > 80:
            die("each review needs a quote (10-400 characters), a name (2-60) and an optional meta line (up to 80)")
    b["reviews"] = [{"quote": r["quote"], "name": r["name"], "meta": r.get("meta", "")} for r in rv]
    return b


def fill(text, b):
    # Brand and founder inside JSON-LD must be JSON-escaped, not HTML-escaped (&amp; would show up literally in structured data).
    jesc = lambda v: json.dumps(v, ensure_ascii=False)[1:-1].replace("<", "\\u003c")
    text = re.sub(r'(<script type="application/ld\+json">)(.*?)(</script>)',
                  lambda m: m.group(1) + m.group(2).replace("[BRAND_NAME]", jesc(b["brand"])).replace("[FOUNDER_NAME]", jesc(b["founder"])) + m.group(3),
                  text, flags=re.S)
    esc = lambda v: v.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")
    pairs = [("+91XXXXXXXXXX", b["phone"]), ("91XXXXXXXXXX", b["whatsapp"]), ("YOUR-DOMAIN.com", b["domain"]),
             ("[BRAND_NAME]", esc(b["brand"])), ("[INSTAGRAM_HANDLE]", b["instagram"]), ("[FOUNDER_NAME]", esc(b["founder"])), ("[LEGAL_NAME]", esc(b["legal_name"])), ("[BUSINESS_ADDRESS]", esc(b["address"])), ("[CONTACT_EMAIL]", b["email"]),
             ("[UDYAM_REG_NO]", b["udyam"])]
    for a, v in pairs:
        text = text.replace(a, v)
    if not b["udyam"]:   # no registration number given: drop the badge rather than show a blank one
        text = re.sub(r'\s*<span class="udyam">.*?</span>', "", text, flags=re.S)
    if b["api_base"]:
        text = text.replace('apiBase: "",', f'apiBase: "{b["api_base"]}",')
    note = "We measure visits to this website with Cloudflare Web Analytics, which counts page views and referring sites without cookies. See Cloudflare's privacy policy for details."
    text = text.replace("[ANALYTICS_NOTE]", note) if b["analytics_token"] else re.sub(r"\s*<p>\[ANALYTICS_NOTE\]</p>", "", text)
    tnote = "Cloudflare Turnstile: checks that a form is filled in by a person, and may process your IP address and browser details. See Cloudflare's privacy policy."
    text = text.replace("[TURNSTILE_NOTE]", tnote) if b["turnstile_site_key"] else re.sub(r"\s*<li>\[TURNSTILE_NOTE\]</li>", "", text)
    if b["turnstile_site_key"]:
        text = text.replace('turnstileSiteKey: "",', f'turnstileSiteKey: "{b["turnstile_site_key"]}",')
    if b["reviews"]:
        text = text.replace("reviews: []", "reviews: " + json.dumps(b["reviews"], ensure_ascii=False).replace("<", "\\u003c"))
    return text


def beacon(b):
    return f"<script defer src=\"https://static.cloudflareinsights.com/beacon.min.js\" data-cf-beacon='{{\"token\": \"{b['analytics_token']}\"}}'></script>\n"


def inline_script_hashes(html):
    out = []
    for m in re.finditer(r"<script(?P<attrs>[^>]*)>(?P<body>.*?)</script>", html, flags=re.S):
        a = m.group("attrs")
        if "src=" in a or re.search(r'type="(?!module)[^"]*json', a):   # external, or JSON-LD (never executed)
            continue
        out.append("'sha256-" + base64.b64encode(hashlib.sha256(m.group("body").encode("utf-8")).digest()).decode() + "'")
    return out


def parse_headers(text):
    """The Cloudflare/Netlify `_headers` format -> [(path pattern, {header: value})]."""
    blocks, cur = [], None
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if not line[0].isspace():
            cur = (line.strip(), {}); blocks.append(cur)
        else:
            k, _, v = line.strip().partition(":")
            cur[1][k.strip()] = v.strip()
    return blocks


def write_vercel(out, dest):
    """Vercel ignores `_headers`, so write the Build Output API: the static site plus a config.json carrying the same headers.
    The CSP lists the hash of every inline script, so it has to be generated here, after the site is built."""
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(out, dest / "static", ignore=shutil.ignore_patterns(MARKER, "_headers"))
    routes = [{"src": "^" + re.escape(pat).replace(r"\*", "(.*)") + "$", "headers": h, "continue": True} for pat, h in parse_headers((out / "_headers").read_text(encoding="utf-8"))]
    slugs = [n.split("/")[0] for n in COPY if n.endswith("/index.html")]
    routes += [{"src": "^/(" + "|".join(slugs) + ")$", "status": 308, "headers": {"Location": "/$1/"}},   # /terms -> /terms/
               {"handle": "filesystem"}, {"src": "/(.*)", "status": 404, "dest": "/404.html"}]
    (dest / "config.json").write_text(json.dumps({"version": 3, "routes": routes}, indent=1), encoding="utf-8")
    print(f"ok: wrote Vercel output {dest} ({len(routes)} routes)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("brand_json")
    ap.add_argument("--out", default=str(ROOT / "dist"))
    ap.add_argument("--allow-example", action="store_true", help="for tests only")
    ap.add_argument("--vercel", action="store_true", help="also write the Vercel Build Output (.vercel/output): the site plus its security headers")
    ap.add_argument("--vercel-out", default=str(ROOT / ".vercel" / "output"), help=argparse.SUPPRESS)
    a = ap.parse_args()
    b = load(a.brand_json, a.allow_example)
    out = Path(a.out).resolve()
    if out.exists():
        if not (out / MARKER).exists():
            die(f"{out} exists and was not created by this tool; refusing to overwrite it")
        shutil.rmtree(out)
    out.mkdir(parents=True)
    (out / MARKER).write_text("generated by tools/personalize.py\n")

    hashes = []
    for name in COPY:
        src = ROOT / name
        if not src.exists():
            die(f"missing {name}")
        if src.is_dir():
            shutil.copytree(src, out / name)
            continue
        if src.suffix in TEXT:
            text = fill(src.read_text(encoding="utf-8"), b)
            if name == "index.html" and b["api_base"] and f'apiBase: "{b["api_base"]}"' not in text:
                die('api_base was not applied: index.html no longer contains \'apiBase: "",\' (update personalize.py to match)')
            if name == "index.html" and b["turnstile_site_key"] and f'turnstileSiteKey: "{b["turnstile_site_key"]}"' not in text:
                die('turnstile_site_key was not applied: index.html no longer contains \'turnstileSiteKey: "",\' (update personalize.py to match)')
            if name == "index.html" and b["reviews"] and "reviews: [{" not in text:
                die('reviews were not applied: index.html no longer contains "reviews: []" (update personalize.py to match)')
            if src.suffix == ".html" and b["analytics_token"]:
                text = text.replace("</body>", beacon(b) + "</body>", 1)
            if name == "sitemap.xml":
                text = re.sub(r"<lastmod>.*?</lastmod>", f"<lastmod>{datetime.date.today().isoformat()}</lastmod>", text)
            (out / name).parent.mkdir(parents=True, exist_ok=True)
            (out / name).write_text(text, encoding="utf-8")
            if src.suffix == ".html":
                hashes += inline_script_hashes(text)
        elif name != "_headers.template":
            shutil.copy2(src, out / name)

    cf = " https://challenges.cloudflare.com" if b["turnstile_site_key"] else ""
    connect = "'self'" + (" " + b["api_base"] if b["api_base"] else "") + (" https://cloudflareinsights.com" if b["analytics_token"] else "") + cf
    script_extra = (" https://static.cloudflareinsights.com" if b["analytics_token"] else "") + cf
    tpl = (ROOT / "_headers.template").read_text(encoding="utf-8")
    (out / "_headers").write_text(tpl.replace("{{SCRIPT_HASHES}}", " ".join(sorted(set(hashes)))).replace("{{SCRIPT_EXTRA}}", script_extra).replace("{{CONNECT_SRC}}", connect).replace("{{FRAME_SRC}}", "'self'" + cf), encoding="utf-8")

    left = []
    for f in out.rglob("*"):
        if f.is_file() and f.suffix in TEXT | {""} and f.name != MARKER:
            t = f.read_text(encoding="utf-8", errors="ignore")
            left += [f"{f.relative_to(out)}: {m}" for m in re.findall(r"\[[A-Z][A-Z_]{3,}\]|YOUR-DOMAIN|91XXXXXXXXXX|yourdomain\.com", t)]
    if left and not a.allow_example:
        die("placeholders still present:\n  " + "\n  ".join(sorted(set(left))))
    if a.vercel:
        write_vercel(out, Path(a.vercel_out))
    print(f"ok: wrote {out}  ({len(set(hashes))} inline script hashes in the CSP)")
    print("next: upload this folder as a static site, then add https://" + b["domain"] + " to the backend's CORS_ORIGINS")


if __name__ == "__main__":
    main()
